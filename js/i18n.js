BM.lang = () => (BM.S && BM.S.settings.lang) || 'de';
BM.gore = () => BM.S && BM.S.settings.content === 'adult';

BM.t = (key, p) => {
  const d = BM.LANG[BM.lang()] || BM.LANG.de;
  let s = (!BM.gore() && d[key + '_soft'] !== undefined) ? d[key + '_soft'] : d[key];
  if (s === undefined) s = BM.LANG.de[key] !== undefined ? BM.LANG.de[key] : key;
  if (p) s = s.replace(/\{(\w+)\}/g, (m, k) => (p[k] !== undefined ? p[k] : m));
  return s;
};
// Objekte der Form {de:'…', en:'…'} (optional de_soft/en_soft)
BM.L = (o) => {
  if (o == null) return '';
  if (typeof o === 'string') return o;
  const l = BM.lang();
  if (!BM.gore() && o[l + '_soft']) return o[l + '_soft'];
  return o[l] || o.de || '';
};
